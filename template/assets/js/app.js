const header=document.querySelector('#siteHeader');
const toggle=document.querySelector('.menu-toggle');
const nav=document.querySelector('#mainNav');
const backdrop=document.querySelector('.nav-backdrop');
const syncHeader=()=>header?.classList.toggle('scrolled',scrollY>24);
addEventListener('scroll',syncHeader,{passive:true});syncHeader();
const setMenu=open=>{toggle?.setAttribute('aria-expanded',String(open));nav?.classList.toggle('open',open);backdrop?.classList.toggle('open',open);document.body.classList.toggle('menu-open',open)};
toggle?.addEventListener('click',()=>setMenu(toggle.getAttribute('aria-expanded')!=='true'));
backdrop?.addEventListener('click',()=>setMenu(false));
document.addEventListener('keydown',event=>{if(event.key==='Escape')setMenu(false)});
nav?.querySelectorAll('a').forEach(link=>link.addEventListener('click',()=>setMenu(false)));
addEventListener('resize',()=>{if(innerWidth>1000)setMenu(false)},{passive:true});
document.querySelectorAll('.nav-dropdown>button').forEach(btn=>btn.addEventListener('click',()=>btn.parentElement.classList.toggle('open')));
document.querySelectorAll('.save').forEach(btn=>btn.addEventListener('click',()=>{btn.classList.toggle('saved');btn.textContent=btn.classList.contains('saved')?'♥':'♡'}));
document.querySelector('.back-top')?.addEventListener('click',()=>scrollTo({top:0,behavior:'smooth'}));
const filter=document.querySelector('#profileFilter');
filter?.addEventListener('input',()=>{const form=new FormData(filter);const city=(form.get('city')||'').toLowerCase(),caste=(form.get('caste')||'').toLowerCase();document.querySelectorAll('.profile-card').forEach(card=>{card.hidden=!!((city&&!card.dataset.city.includes(city))||(caste&&!card.dataset.caste.includes(caste)))});});
const observer=new IntersectionObserver(entries=>entries.forEach(e=>e.isIntersecting&&e.target.classList.add('revealed')),{threshold:.12});
document.querySelectorAll('.reveal').forEach(el=>observer.observe(el));
